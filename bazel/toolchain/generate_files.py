#!/usr/bin/env python3
"""Generate the checked-in Bazel, CMake and Conan views of Forge's presets."""

import argparse
import difflib
import json
from pathlib import Path
import pprint

HERE = Path(__file__).resolve().parent
GCC_VERSION = "13"
SDK_PATH = "/opt/eros"
SANITIZERS = ["asan", "ubsan", "tsan", "asan_ubsan"]
SANITIZER_FEATURES = {
    "none": [], "asan": ["asan"], "ubsan": ["ubsan"],
    "tsan": ["tsan"], "asan_ubsan": ["asan", "ubsan"],
}
SANITIZER_FLAGS = {
    "none": [], "asan": ["-fsanitize=address"], "ubsan": ["-fsanitize=undefined"],
    "tsan": ["-fsanitize=thread"], "asan_ubsan": ["-fsanitize=address,undefined"],
}
TOOL_NAMES = ["gcc", "g++", "ld", "ar", "as", "cpp", "gcov", "nm", "objdump", "objcopy", "strip", "dwp", "ranlib", "readelf"]
EROS_TOOLCHAINS = {}
for name, host, target, cross in [
    ("linux_x86_64", "x86_64", "x86_64", False),
    ("linux_arm64", "arm64", "arm64", False),
    ("linux_x86_64_cross_arm64", "x86_64", "arm64", True),
    ("linux_arm64_cross_arm64", "arm64", "arm64", True),
]:
    EROS_TOOLCHAINS[name] = {
        "host_cpu": host, "target_cpu": target,
        "host_triple": ("aarch64" if host == "arm64" else "x86_64") + "-linux-gnu",
        "target_triple": ("aarch64" if target == "arm64" else "x86_64") + "-linux-gnu",
        "conan_arch": "armv8" if target == "arm64" else "x86_64",
        "build_arch": "armv8" if host == "arm64" else "x86_64",
        "processor": "aarch64" if target == "arm64" else "x86_64",
        "compiler_prefix": "aarch64-linux-gnu-" if cross else "",
        "tools_set": "cross_arm64" if cross else "native",
        "is_cross": cross,
        "sdk_path": SDK_PATH if cross else "",
        "dynamic_interpreter": SDK_PATH + "/lib/ld-linux-aarch64.so.1" if cross else "",
    }


def tool_path(cfg, tool):
    suffix = "-" + GCC_VERSION if tool in ["gcc", "g++", "cpp", "gcov"] else ""
    return "/usr/bin/" + cfg["compiler_prefix"] + tool + suffix


def compile_flags(cfg, mode, sanitizer="none"):
    flags = ["-g", "-fno-omit-frame-pointer"]
    flags += ["-O0"] if mode == "debug" else ["-O3", "-DNDEBUG"]
    if cfg["is_cross"]:
        flags.append("-B/usr/bin/aarch64-linux-gnu-")
    return flags + SANITIZER_FLAGS[sanitizer]


def link_flags(cfg, sanitizer="none", executable=True):
    flags = list(SANITIZER_FLAGS[sanitizer])
    if cfg["is_cross"]:
        flags += ["-B/usr/bin/aarch64-linux-gnu-", "-Wl,-rpath," + SDK_PATH + "/lib"]
        if executable:
            flags.append("-Wl,--dynamic-linker=" + cfg["dynamic_interpreter"])
    return flags


def profile(cfg, mode, sanitizer="none", build=False):
    if build:
        cfg = dict(cfg, conan_arch=cfg["build_arch"], is_cross=False, compiler_prefix="")
    lines = [
        "# Generated by bazel/toolchain/generate_files.py. Do not edit.",
        "[settings]", "os=Linux", "arch=" + cfg["conan_arch"],
        "compiler=gcc", "compiler.version=" + GCC_VERSION, "compiler.libcxx=libstdc++11",
        "compiler.cppstd=gnu20", "build_type=" + ("Debug" if mode == "debug" else "Release"),
        "", "[options]", "*:shared=False", "*:fPIC=True", "", "[conf]",
        "tools.cmake.cmaketoolchain:generator=Unix Makefiles",
        "tools.build:compiler_executables=" + json.dumps({"c": tool_path(cfg, "gcc"), "cpp": tool_path(cfg, "g++"), "asm": tool_path(cfg, "gcc")}),
    ]
    flags = compile_flags(cfg, mode, sanitizer)
    for key in ["cflags", "cxxflags"]:
        lines.append("tools.build:" + key + "=" + json.dumps(flags))
    for key, executable in [("exelinkflags", True), ("sharedlinkflags", False)]:
        lines.append("tools.build:" + key + "=" + json.dumps(link_flags(cfg, sanitizer, executable)))
    lines.append("tools.info.package_id:confs=" + json.dumps(["tools.build:*", "user.eros:*"]))
    if cfg["is_cross"]:
        lines += [
            "tools.cmake.cmaketoolchain:system_name=Linux",
            "tools.cmake.cmaketoolchain:system_processor=" + cfg["processor"],
        ]
    return "\n".join(lines) + "\n"


def cmake_toolchain(cfg):
    lines = [
        "# Generated by bazel/toolchain/generate_files.py. Do not edit.",
        'if(NOT CMAKE_HOST_SYSTEM_NAME STREQUAL "Linux")',
        '  message(FATAL_ERROR "Forge requires a Linux execution host")', "endif()",
        'if(NOT CMAKE_HOST_SYSTEM_PROCESSOR MATCHES "' + ("^(aarch64|arm64)$" if cfg["host_cpu"] == "arm64" else "^(x86_64|amd64|AMD64)$") + '")',
        '  message(FATAL_ERROR "Forge preset requires a ' + cfg["host_cpu"] + ' execution host")', "endif()",
    ]
    if cfg["is_cross"]:
        lines += ["set(CMAKE_SYSTEM_NAME Linux)", "set(CMAKE_SYSTEM_PROCESSOR aarch64)"]
    for variable, tool in [
        ("C_COMPILER", "gcc"), ("CXX_COMPILER", "g++"), ("ASM_COMPILER", "gcc"),
        ("AR", "ar"), ("LINKER", "ld"), ("NM", "nm"), ("OBJCOPY", "objcopy"),
        ("OBJDUMP", "objdump"), ("RANLIB", "ranlib"), ("STRIP", "strip"), ("READELF", "readelf"),
    ]:
        lines.append('set(CMAKE_' + variable + ' "' + tool_path(cfg, tool) + '")')
    lines += [
        "set(CMAKE_CXX_STANDARD 20)", "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
        'set(CMAKE_C_FLAGS_DEBUG_INIT "-O0 -g -fno-omit-frame-pointer")',
        'set(CMAKE_CXX_FLAGS_DEBUG_INIT "-O0 -g -fno-omit-frame-pointer")',
        'set(CMAKE_C_FLAGS_RELEASE_INIT "-O3 -DNDEBUG -g -fno-omit-frame-pointer")',
        'set(CMAKE_CXX_FLAGS_RELEASE_INIT "-O3 -DNDEBUG -g -fno-omit-frame-pointer")',
    ]
    if cfg["is_cross"]:
        for language in ["C", "CXX", "ASM"]:
            lines.append('set(CMAKE_' + language + '_FLAGS_INIT "-B/usr/bin/aarch64-linux-gnu-")')
        for variable, executable in [("EXE", True), ("SHARED", False), ("MODULE", False)]:
            lines.append('set(CMAKE_' + variable + '_LINKER_FLAGS_INIT "' + " ".join(link_flags(cfg, executable=executable)) + '")')
        lines += [
            "# The controlled compiler supplies headers/libraries; /opt/eros is the deployment runtime.",
            "# Keep executable try_compile checks; never fake try_run results.",
            "set(CMAKE_FIND_ROOT_PATH /usr/aarch64-linux-gnu /opt/eros)",
            "set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)",
            "set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)",
            "set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)",
            "set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)",
        ]
    lines.append("# EROS_FORGE_FLAGS")
    return "\n".join(lines) + "\n"


def generated_files():
    data = "# Generated by generate_files.py. Do not edit.\n\n"
    for name in ["GCC_VERSION", "SDK_PATH", "SANITIZERS", "SANITIZER_FEATURES", "SANITIZER_FLAGS", "TOOL_NAMES", "EROS_TOOLCHAINS"]:
        data += name + " = " + pprint.pformat(globals()[name], width=100, sort_dicts=False) + "\n\n"
    result = {HERE / "toolchain_data.bzl": data.rstrip() + "\n"}
    spec = {
        "schema_version": 1, "gcc_major": GCC_VERSION, "sdk_path": SDK_PATH,
        "expected_versions": {"bazel": "9.0.0", "cmake": "4.4.4", "conan": "2.25.2", "python_major": "3"},
        "presets": EROS_TOOLCHAINS, "tool_names": TOOL_NAMES,
    }
    result[HERE / "environment_spec.json"] = json.dumps(spec, indent=2) + "\n"
    for preset, cfg in EROS_TOOLCHAINS.items():
        for mode in ["release", "debug"]:
            result[HERE / "conan" / (preset + "_" + mode + ".profile")] = profile(cfg, mode)
            result[HERE / "conan" / (preset + "_build_" + mode + ".profile")] = profile(cfg, mode, build=True)
        for sanitizer in SANITIZERS:
            result[HERE / "conan" / (preset + "_" + sanitizer + ".profile")] = profile(cfg, "debug", sanitizer)
        result[HERE / "cmake" / (preset + ".cmake")] = cmake_toolchain(cfg)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail without writing if generated files have drifted.")
    args = parser.parse_args()
    expected = generated_files()
    actual = set((HERE / "conan").glob("*.profile")) | set((HERE / "cmake").glob("*.cmake"))
    stale = actual - set(expected)
    failed = False
    for path, content in expected.items():
        if args.check:
            old = path.read_text() if path.exists() else ""
            if old != content:
                failed = True
                print("".join(difflib.unified_diff(old.splitlines(True), content.splitlines(True), fromfile=str(path), tofile="generated")), end="")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    for path in sorted(stale):
        if args.check:
            print("Unexpected generated file: " + str(path))
            failed = True
        else:
            path.unlink()
    if failed:
        parser.exit(1, "Generated Forge configuration drift; run python3 bazel/toolchain/generate_files.py\n")
    print(("Checked " if args.check else "Generated ") + str(len(expected)) + " Forge configuration files")


if __name__ == "__main__":
    main()
